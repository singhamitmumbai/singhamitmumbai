"""Template-based code generation — functions, classes, tests, modules (non-LLM)."""

from __future__ import annotations

import re
from textwrap import dedent
from typing import Any, Optional


def generate_function(
    name: str,
    *,
    args: Optional[list[str]] = None,
    returns: Optional[str] = None,
    docstring: Optional[str] = None,
    body: Optional[str] = None,
    decorators: Optional[list[str]] = None,
    implement: bool = True,
) -> str:
    name = _safe_ident(name)
    args = [_safe_ident(a.split(":")[0].strip()) for a in (args or [])]
    inferred = _infer_implementation(name, args) if implement and body is None else None
    if inferred:
        returns = returns or inferred.get("returns") or "None"
        body = inferred["body"]
        docstring = docstring or inferred.get("docstring")
    returns = returns or "None"
    arglist = ", ".join(args)
    doc = docstring or f"{name} — generated by non-LLM CodingSystem."
    body = body or "    raise NotImplementedError\n"
    if not body.startswith(" "):
        body = "\n".join("    " + ln if ln.strip() else ln for ln in body.splitlines()) + "\n"
    if not body.endswith("\n"):
        body += "\n"
    decos = "".join(f"@{d}\n" for d in (decorators or []))
    return (
        f"{decos}def {name}({arglist}) -> {returns}:\n"
        f'    """{doc}"""\n'
        f"{body}"
    )


def generate_class(
    name: str,
    *,
    bases: Optional[list[str]] = None,
    docstring: Optional[str] = None,
    methods: Optional[list[dict[str, Any]]] = None,
    attributes: Optional[dict[str, str]] = None,
) -> str:
    name = _safe_ident(name, capitalize=True)
    bases = bases or []
    base_s = f"({', '.join(bases)})" if bases else ""
    doc = docstring or f"{name} — generated by non-LLM CodingSystem."
    lines = [f"class {name}{base_s}:", f'    """{doc}"""', ""]
    for k, v in (attributes or {}).items():
        lines.append(f"    { _safe_ident(k) } = {v}")
    if attributes:
        lines.append("")
    methods = methods or [{"name": "__init__", "args": ["self"], "body": "    pass\n"}]
    for m in methods:
        margs = m.get("args") or ["self"]
        if "self" not in margs and not m.get("staticmethod"):
            margs = ["self", *margs]
        fn = generate_function(
            m["name"],
            args=margs,
            returns=m.get("returns", "None"),
            docstring=m.get("docstring"),
            body=m.get("body") or "    pass\n",
            decorators=m.get("decorators"),
        )
        # indent function into class
        indented = "\n".join(("    " + ln if ln else ln) for ln in fn.splitlines())
        lines.append(indented)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generate_module(
    name: str,
    *,
    docstring: Optional[str] = None,
    imports: Optional[list[str]] = None,
    functions: Optional[list[dict[str, Any]]] = None,
    classes: Optional[list[dict[str, Any]]] = None,
) -> str:
    parts = [
        f'"""{docstring or f"{name} module — generated by non-LLM CodingSystem."}"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for imp in imports or []:
        parts.append(imp if imp.startswith(("import ", "from ")) else f"import {imp}")
    if imports:
        parts.append("")
    for fn in functions or []:
        parts.append(
            generate_function(
                fn["name"],
                args=fn.get("args"),
                returns=fn.get("returns", "None"),
                docstring=fn.get("docstring"),
                body=fn.get("body"),
                decorators=fn.get("decorators"),
            )
        )
        parts.append("")
    for cls in classes or []:
        parts.append(
            generate_class(
                cls["name"],
                bases=cls.get("bases"),
                docstring=cls.get("docstring"),
                methods=cls.get("methods"),
                attributes=cls.get("attributes"),
            )
        )
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def generate_pytest(
    target_name: str,
    *,
    module: Optional[str] = None,
    cases: Optional[list[dict[str, Any]]] = None,
) -> str:
    """Generate a minimal pytest module for a function/class."""
    target_name = _safe_ident(target_name)
    mod = module or target_name
    cases = cases or [{"name": "smoke", "call": f"{target_name}()", "assert": "True"}]
    lines = [
        f'"""Tests for {target_name} — generated by non-LLM CodingSystem."""',
        "",
        f"from {mod} import {target_name}",
        "",
        "",
    ]
    for c in cases:
        cname = _safe_ident(c.get("name") or "case")
        call = c.get("call") or f"{target_name}()"
        assertion = c.get("assert") or "True"
        lines.append(f"def test_{cname}():")
        if c.get("raises"):
            lines.append("    import pytest")
            lines.append(f"    with pytest.raises({c['raises']}):")
            lines.append(f"        {call}")
        else:
            lines.append(f"    result = {call}")
            lines.append(f"    assert {assertion}")
        lines.append("")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generate_dataclass(name: str, fields: dict[str, str], *, docstring: Optional[str] = None) -> str:
    name = _safe_ident(name, capitalize=True)
    doc = docstring or f"{name} dataclass."
    lines = [
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass",
        f"class {name}:",
        f'    """{doc}"""',
    ]
    for k, typ in fields.items():
        lines.append(f"    {_safe_ident(k)}: {typ}")
    return "\n".join(lines) + "\n"


def parse_generate_request(text: str) -> Optional[dict[str, Any]]:
    """Map natural-ish coding instructions to a generate plan (pattern-based)."""
    lower = text.lower().strip()
    # implement / def-style
    m = re.search(
        r"(?:implement|generate|create|write|make)\s+(?:a\s+)?(?:python\s+)?function\s+(\w+)(?:\s*\(([^)]*)\))?",
        lower,
    )
    if m:
        args = [a.strip() for a in (m.group(2) or "").split(",") if a.strip()]
        return {"action": "generate_function", "name": m.group(1), "args": args, "implement": True}
    m = re.search(r"\bdef\s+(\w+)\s*\(([^)]*)\)", text)
    if m and re.search(r"\b(?:generate|create|write|implement|coding)\b", lower):
        args = [a.strip() for a in (m.group(2) or "").split(",") if a.strip()]
        return {"action": "generate_function", "name": m.group(1), "args": args, "implement": True}
    m = re.search(r"(?:generate|create|write)\s+class\s+(\w+)", lower)
    if m:
        return {"action": "generate_class", "name": m.group(1)}
    m = re.search(r"(?:generate|create|write|add)\s+test(?:s)?\s+(?:for\s+)?(\w+)", lower)
    if m:
        return {"action": "generate_test", "name": m.group(1)}
    m = re.search(r"(?:generate|create|write)\s+module\s+(\w+)", lower)
    if m:
        return {"action": "generate_module", "name": m.group(1)}
    m = re.search(r"(?:generate|create)\s+dataclass\s+(\w+)", lower)
    if m:
        return {"action": "generate_dataclass", "name": m.group(1)}
    m = re.search(r"(?:generate|create)\s+enum\s+(\w+)", lower)
    if m:
        return {"action": "generate_enum", "name": m.group(1)}
    return None


def generate_enum(name: str, members: Optional[list[str]] = None, *, docstring: Optional[str] = None) -> str:
    name = _safe_ident(name, capitalize=True)
    members = members or ["PENDING", "RUNNING", "DONE", "FAILED"]
    doc = docstring or f"{name} enumeration."
    lines = [
        "from __future__ import annotations",
        "",
        "from enum import Enum",
        "",
        "",
        f"class {name}(str, Enum):",
        f'    """{doc}"""',
    ]
    for m in members:
        key = _safe_ident(m).upper()
        lines.append(f'    {key} = "{key.lower()}"')
    return "\n".join(lines) + "\n"


def _infer_implementation(name: str, args: list[str]) -> Optional[dict[str, Any]]:
    """Deterministic bodies for common pure functions — improves stability vs NotImplementedError."""
    n = name.lower()
    a = args
    if n in ("add", "sum2", "plus") and len(a) >= 2:
        return {
            "returns": "float",
            "docstring": f"Return {a[0]} + {a[1]}.",
            "body": f"    return {a[0]} + {a[1]}\n",
        }
    if n in ("sub", "subtract", "minus") and len(a) >= 2:
        return {
            "returns": "float",
            "docstring": f"Return {a[0]} - {a[1]}.",
            "body": f"    return {a[0]} - {a[1]}\n",
        }
    if n in ("mul", "multiply", "times", "product") and len(a) >= 2:
        return {
            "returns": "float",
            "docstring": f"Return {a[0]} * {a[1]}.",
            "body": f"    return {a[0]} * {a[1]}\n",
        }
    if n in ("div", "divide", "truediv") and len(a) >= 2:
        return {
            "returns": "float",
            "docstring": f"Return {a[0]} / {a[1]} (raises on zero).",
            "body": (
                f"    if {a[1]} == 0:\n"
                f"        raise ZeroDivisionError(\"{a[1]} must not be 0\")\n"
                f"    return {a[0]} / {a[1]}\n"
            ),
        }
    if n in ("abs_val", "absolute") and len(a) >= 1:
        return {"returns": "float", "docstring": f"Absolute value of {a[0]}.", "body": f"    return abs({a[0]})\n"}
    if n in ("identity", "id_") and len(a) >= 1:
        return {"returns": "object", "docstring": "Return the input unchanged.", "body": f"    return {a[0]}\n"}
    if n in ("is_even",) and len(a) >= 1:
        return {"returns": "bool", "docstring": f"True if {a[0]} is even.", "body": f"    return {a[0]} % 2 == 0\n"}
    if n in ("is_odd",) and len(a) >= 1:
        return {"returns": "bool", "docstring": f"True if {a[0]} is odd.", "body": f"    return {a[0]} % 2 != 0\n"}
    if n in ("clamp",) and len(a) >= 3:
        return {
            "returns": "float",
            "docstring": f"Clamp {a[0]} between {a[1]} and {a[2]}.",
            "body": f"    return max({a[1]}, min({a[2]}, {a[0]}))\n",
        }
    if n in ("greet", "hello") and len(a) >= 1:
        return {
            "returns": "str",
            "docstring": f"Greeting for {a[0]}.",
            "body": f'    return f"Hello, {{{a[0]}}}!"\n',
        }
    if n in ("main",) and not a:
        return {"returns": "int", "docstring": "Module entrypoint.", "body": "    return 0\n"}
    if n.startswith("get_") and len(a) >= 1:
        # soft default
        return {
            "returns": "object",
            "docstring": f"Return field from {a[0]} if mapping-like.",
            "body": (
                f"    key = \"{n[4:]}\"\n"
                f"    if isinstance({a[0]}, dict):\n"
                f"        return {a[0]}.get(key)\n"
                f"    return getattr({a[0]}, key, None)\n"
            ),
        }
    return None


def _safe_ident(name: str, *, capitalize: bool = False) -> str:
    cleaned = re.sub(r"\W+", "_", name.strip())
    cleaned = re.sub(r"^[^A-Za-z_]+", "", cleaned) or "generated"
    if cleaned in {"class", "def", "return", "import", "from", "pass", "None", "True", "False"}:
        cleaned = cleaned + "_"
    if capitalize and cleaned:
        cleaned = cleaned[0].upper() + cleaned[1:]
    return cleaned
