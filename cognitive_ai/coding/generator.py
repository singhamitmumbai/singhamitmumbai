"""Template-based code generation — functions, classes, tests, modules (non-LLM)."""

from __future__ import annotations

import re
from textwrap import dedent
from typing import Any, Optional


def generate_function(
    name: str,
    *,
    args: Optional[list[str]] = None,
    returns: str = "None",
    docstring: Optional[str] = None,
    body: Optional[str] = None,
    decorators: Optional[list[str]] = None,
) -> str:
    name = _safe_ident(name)
    args = args or []
    arglist = ", ".join(args)
    doc = docstring or f"{name} — generated by non-LLM CodingSystem."
    body = body or "    raise NotImplementedError\n"
    if not body.startswith(" "):
        body = "\n".join("    " + ln if ln.strip() else ln for ln in body.splitlines()) + "\n"
    decos = "".join(f"@{d}\n" for d in (decorators or []))
    return (
        f"{decos}def {name}({arglist}) -> {returns}:\n"
        f'    """{doc}"""\n'
        f"{body}"
    )


def generate_class(
    name: str,
    *,
    bases: Optional[list[str]] = None,
    docstring: Optional[str] = None,
    methods: Optional[list[dict[str, Any]]] = None,
    attributes: Optional[dict[str, str]] = None,
) -> str:
    name = _safe_ident(name, capitalize=True)
    bases = bases or []
    base_s = f"({', '.join(bases)})" if bases else ""
    doc = docstring or f"{name} — generated by non-LLM CodingSystem."
    lines = [f"class {name}{base_s}:", f'    """{doc}"""', ""]
    for k, v in (attributes or {}).items():
        lines.append(f"    { _safe_ident(k) } = {v}")
    if attributes:
        lines.append("")
    methods = methods or [{"name": "__init__", "args": ["self"], "body": "    pass\n"}]
    for m in methods:
        margs = m.get("args") or ["self"]
        if "self" not in margs and not m.get("staticmethod"):
            margs = ["self", *margs]
        fn = generate_function(
            m["name"],
            args=margs,
            returns=m.get("returns", "None"),
            docstring=m.get("docstring"),
            body=m.get("body") or "    pass\n",
            decorators=m.get("decorators"),
        )
        # indent function into class
        indented = "\n".join(("    " + ln if ln else ln) for ln in fn.splitlines())
        lines.append(indented)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generate_module(
    name: str,
    *,
    docstring: Optional[str] = None,
    imports: Optional[list[str]] = None,
    functions: Optional[list[dict[str, Any]]] = None,
    classes: Optional[list[dict[str, Any]]] = None,
) -> str:
    parts = [
        f'"""{docstring or f"{name} module — generated by non-LLM CodingSystem."}"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for imp in imports or []:
        parts.append(imp if imp.startswith(("import ", "from ")) else f"import {imp}")
    if imports:
        parts.append("")
    for fn in functions or []:
        parts.append(
            generate_function(
                fn["name"],
                args=fn.get("args"),
                returns=fn.get("returns", "None"),
                docstring=fn.get("docstring"),
                body=fn.get("body"),
                decorators=fn.get("decorators"),
            )
        )
        parts.append("")
    for cls in classes or []:
        parts.append(
            generate_class(
                cls["name"],
                bases=cls.get("bases"),
                docstring=cls.get("docstring"),
                methods=cls.get("methods"),
                attributes=cls.get("attributes"),
            )
        )
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def generate_pytest(
    target_name: str,
    *,
    module: Optional[str] = None,
    cases: Optional[list[dict[str, Any]]] = None,
) -> str:
    """Generate a minimal pytest module for a function/class."""
    target_name = _safe_ident(target_name)
    mod = module or target_name
    cases = cases or [{"name": "smoke", "call": f"{target_name}()", "assert": "True"}]
    lines = [
        f'"""Tests for {target_name} — generated by non-LLM CodingSystem."""',
        "",
        f"from {mod} import {target_name}",
        "",
        "",
    ]
    for c in cases:
        cname = _safe_ident(c.get("name") or "case")
        call = c.get("call") or f"{target_name}()"
        assertion = c.get("assert") or "True"
        lines.append(f"def test_{cname}():")
        if c.get("raises"):
            lines.append("    import pytest")
            lines.append(f"    with pytest.raises({c['raises']}):")
            lines.append(f"        {call}")
        else:
            lines.append(f"    result = {call}")
            lines.append(f"    assert {assertion}")
        lines.append("")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generate_dataclass(name: str, fields: dict[str, str], *, docstring: Optional[str] = None) -> str:
    name = _safe_ident(name, capitalize=True)
    doc = docstring or f"{name} dataclass."
    lines = [
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass",
        f"class {name}:",
        f'    """{doc}"""',
    ]
    for k, typ in fields.items():
        lines.append(f"    {_safe_ident(k)}: {typ}")
    return "\n".join(lines) + "\n"


def parse_generate_request(text: str) -> Optional[dict[str, Any]]:
    """Map natural-ish coding instructions to a generate plan (pattern-based)."""
    lower = text.lower().strip()
    m = re.search(r"(?:generate|create|write)\s+function\s+(\w+)(?:\s*\(([^)]*)\))?", lower)
    if m:
        args = [a.strip() for a in (m.group(2) or "").split(",") if a.strip()]
        return {"action": "generate_function", "name": m.group(1), "args": args}
    m = re.search(r"(?:generate|create|write)\s+class\s+(\w+)", lower)
    if m:
        return {"action": "generate_class", "name": m.group(1)}
    m = re.search(r"(?:generate|create|write|add)\s+test(?:s)?\s+(?:for\s+)?(\w+)", lower)
    if m:
        return {"action": "generate_test", "name": m.group(1)}
    m = re.search(r"(?:generate|create|write)\s+module\s+(\w+)", lower)
    if m:
        return {"action": "generate_module", "name": m.group(1)}
    m = re.search(r"(?:generate|create)\s+dataclass\s+(\w+)", lower)
    if m:
        return {"action": "generate_dataclass", "name": m.group(1)}
    return None


def _safe_ident(name: str, *, capitalize: bool = False) -> str:
    cleaned = re.sub(r"\W+", "_", name.strip())
    cleaned = re.sub(r"^[^A-Za-z_]+", "", cleaned) or "generated"
    if capitalize and cleaned:
        cleaned = cleaned[0].upper() + cleaned[1:]
    return cleaned
